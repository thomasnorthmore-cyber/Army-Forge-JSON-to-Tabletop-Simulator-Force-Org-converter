import assert from 'node:assert/strict';
import {createWorker,newCode,buildImport} from '../src/worker.mjs';
import {webcrypto} from 'node:crypto';
const book={uid:'b',gameSystemSlug:'grimdark-future',versionString:'3.6.1',units:[{id:'u',name:'Squad',size:1,quality:3,defense:4,cost:100,upgrades:[],weapons:[{name:'Blade',range:0,attacks:1,count:1}],rules:[{name:'Tough',rating:3}]}],upgradePackages:[]};
const roster={gameSystem:'gf',armyVersions:[{armyId:'b',version:'3.6.1'}],listPoints:100,list:{name:'Test',modelCount:1,units:[{id:'u',armyId:'b',selectionId:'s',selectedUpgrades:[]}]}};
let time=1000000,fetches=0;
const records=new Map(),ttls=[];
const env={ARMIES:{get:async k=>records.get(k)??null,put:async(k,v,o)=>{records.set(k,v);ttls.push(o.expirationTtl)}}};
const worker=createWorker({now:()=>time,random:webcrypto,fetchBook:async()=>{fetches++;return book}});
const origin='https://example.test';
const post=(input,headers={})=>worker.fetch(new Request(origin+'/api/upload',{method:'POST',headers:{'content-type':'application/json',...headers},body:JSON.stringify(input)}),env);
const get=code=>worker.fetch(new Request(origin+'/api/army?code='+encodeURIComponent(code)),env);
assert.match(newCode(webcrypto),/^OPR-[A-HJ-NP-Z2-9]{9}$/);
const response=await post({roster,book});assert.equal(response.status,200);
const result=await response.json();assert.match(result.code,/^OPR-[A-HJ-NP-Z2-9]{9}$/);
assert.equal(result.expiresInSeconds,600);
assert.equal(result.expiresAt,time+600000);
assert.equal(ttls[0],600);
assert.equal(result.models,1);
const loaded=await get(result.code.toLowerCase());assert.equal(loaded.status,200);
const data=await loaded.json();assert.equal(data.listId,result.code);
assert.equal(data.listJson.units[0].modelDefinitions[0].originalToughValue,3);
assert.equal(Object.hasOwn(data,'roster'),false);
assert.equal((await get('INVALID')).status,400);
assert.equal((await post({roster:{...roster,listPoints:105},book})).status,400);
assert.equal((await post({roster:{...roster,armyVersions:[{armyId:'b',version:'3.6.0'}]},book})).status,400);
assert.equal((await post({roster,book},{origin:'https://other.test'})).status,403);
assert.equal((await post({listJson:data.listJson})).status,400);
assert.equal(records.size,1);
const automatic=await post({roster});assert.equal(automatic.status,200);
assert.equal(fetches,1);
const second=await automatic.json();assert.notEqual(second.code,result.code);
const data2=await (await get(second.code)).json();assert.notEqual(data2.listJson.units[0].unitId,data.listJson.units[0].unitId);
time=result.expiresAt-1;assert.equal((await get(result.code)).status,200);
time=result.expiresAt;assert.equal((await get(result.code)).status,404);
assert.equal((await worker.fetch(new Request(origin+'/api/army?code='+result.code),{})).status,503);
assert.throws(()=>buildImport({...roster,list:{...roster.list,modelCount:2}},book),/Model count mismatch/);
const preview=await worker.fetch(new Request(origin+'/api/preview',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({roster})}),{});
assert.equal(preview.status,200);
const previewData=await preview.json();
assert.equal(previewData.resolved.computedPoints,100);
assert.equal(previewData.resolved.modelCount,1);
assert.equal(Object.hasOwn(previewData,'book'),false);
assert.equal(records.size,2);
assert.equal(fetches,2);
const refused=await worker.fetch(new Request(origin+'/api/preview',{method:'POST',headers:{'content-type':'application/json',origin:'https://other.test'},body:JSON.stringify({roster})}),{});
assert.equal(refused.status,403);
const down=createWorker({fetchBook:async()=>{throw Error('Upstream unavailable')}});
assert.equal((await down.fetch(new Request(origin+'/api/preview',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({roster})}),{})).status,502);
console.log('33 code service and preview assertions passed');
